# Writes Fixture.kt from tools/fixture/fixture.json: the sample people and posts the screens show until the app is
# connected to the server. The web reference screenshots (tools/refweb.js) use the same file, so both can be compared.
import json, os, datetime
here = os.path.dirname(os.path.abspath(__file__))
f = json.load(open(os.path.join(here, 'fixture', 'fixture.json')))
now = datetime.datetime.fromisoformat(f['now'].replace('Z', '+00:00'))
def ago(m):  # the same rules as ago() in app.js
    if m < 1: return 'now'
    if m < 60: return f'{m}m'
    h = m // 60
    if h < 24: return f'{h}h'
    return f'{h // 24}d'
def when(m):  # toLocaleString([], { dateStyle: "medium", timeStyle: "short" }) in en-US
    t = now - datetime.timedelta(minutes=m)
    return t.strftime('%b ') + str(t.day) + t.strftime(', %Y, ') + str(int(t.strftime('%I'))) + t.strftime(':%M %p')
q = lambda s: json.dumps(s, ensure_ascii=False).replace('$', '\\$')
people = '\n'.join(f'    val p{i} = Person({q(p["id"])}, {q(p["name"])}, {q(p["handle"])}, {q(p["bio"])}, own = {str(p["id"] == f["me"]).lower()})' for i, p in enumerate(f['people']))
posts = ',\n'.join(f'        Post({q(p["id"])}, p{p["by"]}, {q(p["body"])}, {q(ago(p["min"]))}, pic = {str(bool(p.get("pic"))).lower()}, parent = {q(p["parent"]) if p.get("parent") else "null"}, time = {q(when(p["min"]))})' for p in f['posts'])
kt = f'''package io.github.nookwebapp.native_ui

import androidx.compose.runtime.mutableStateListOf

// generated by tools/genfixture.py from tools/fixture/fixture.json; do not edit by hand
object Sample {{
{people}
    val me = p0
    val people = listOf({", ".join(f"p{i}" for i in range(1, len(f["people"])))})
    val posts = mutableStateListOf(
{posts},
    )
    val placeholder = {q(f["placeholder"])}
}}
'''
open(os.path.join(here, '..', 'app/src/main/java/io/github/nookwebapp/native_ui/Fixture.kt'), 'w').write(kt)
print('Fixture.kt written')
