# Writes the test Fixture.kt from tools/fixture/fixture.json: the sample posts the screenshot tests put in the local store.
# The web reference screenshots (tools/refweb.js) serve the same file, so both sides draw the same thing.
import json, os
here = os.path.dirname(os.path.abspath(__file__))
f = json.load(open(os.path.join(here, 'fixture', 'fixture.json')))
import datetime
now = int(datetime.datetime.fromisoformat(f['now'].replace('Z', '+00:00')).timestamp() * 1000)
q = lambda s: json.dumps(s, ensure_ascii=False).replace('$', '\\$')
me = f['people'][0]
posts = '\n'.join(
    f'        s.posts.add(LPost({q(p["id"])}, {q(p["body"])}, NOW - {p["min"]}L * 60000, {"listOf(PIC)" if p.get("pic") else "emptyList()"}, {q(p["parent"]) if p.get("parent") else "null"}))'
    for p in f['posts'])
kt = f'''package io.github.nookwebapp.native_ui

// generated by tools/genfixture.py from tools/fixture/fixture.json; do not edit by hand
object Sample {{
    const val NOW = {now}L
    val PIC: String = java.io.File("src/test/resources/sample_pic.png").absolutePath
    val placeholder = {q(f["placeholder"])}
    fun seed(s: Store) {{
        s.signedIn = true
        s.profile.name = {q(me["name"])}; s.profile.handle = {q(me["handle"])}; s.profile.bio = {q(me["bio"])}
{posts}
    }}
}}
'''
open(os.path.join(here, '..', 'app/src/test/java/io/github/nookwebapp/native_ui/Fixture.kt'), 'w').write(kt)
print('Fixture.kt written')
