// Writes Legal.kt from the LEGAL texts and the composer prompts in app.js, so the native Terms and Privacy pages say exactly what the web app says.
// usage: node tools/genlegal.js
const fs = require("fs"), path = require("path");
const src = fs.readFileSync(path.join(__dirname, "../../app.js"), "utf8");
const a = src.indexOf("const LEGAL = {"), b = src.indexOf("\n};", a);
const LEGAL = new Function(src.slice(a, b + 3).replace("const LEGAL =", "return") )();
const pa = src.indexOf("const PH = ["), pb = src.indexOf("];", pa);
const PH = new Function("return " + src.slice(pa + "const PH = ".length, pb + 1))();
const q = s => JSON.stringify(s).replace(/\$/g, "\\$");
const doc = d => `LegalDoc(${q(d.title)}, listOf(\n${d.body.map(([h, items]) => `        ${q(h)} to listOf(${items.map(q).join(", ")}),`).join("\n")}\n    ))`;
const out = `package io.github.nookwebapp.native_ui

// generated by tools/genlegal.js from LEGAL in app.js; do not edit by hand
class LegalDoc(val title: String, val body: List<Pair<String, List<String>>>)
val TERMS = ${doc(LEGAL.terms)}
val PRIVACY = ${doc(LEGAL.privacy)}
// the composer prompts (PH in app.js); one is picked when the app starts
val PH = listOf(${PH.map(q).join(", ")})
`;
fs.writeFileSync(path.join(__dirname, "../app/src/main/java/io/github/nookwebapp/native_ui/Legal.kt"), out);
console.log("Legal.kt written");
